def main():
    # catalog.py's own reader and writer: a long English id is wrapped over several lines in the .po, which a
    # one-line pattern missed (four of the GameBanana tab's texts on 13/11/2026)
    import sys

    sys.path.insert(0, str(ROOT / "tools/i18n"))
    import catalog

    changed = 0
    langs = sorted({lang for t in T.values() for lang in t})
    for lang in langs:
        path = I18N / f"{lang}.po"
        header, entries = catalog.parse(path)
        for e in entries:
            if not e.msgstr and lang in T.get(e.ctx, {}):   # only empty ones: never a translator's words
                e.msgstr = T[e.ctx][lang].replace('"', '\\"')
                changed += 1
        catalog.write(path, header, entries)
    print(f"filled {changed} empty entries")


if __name__ == "__main__":
    main()
