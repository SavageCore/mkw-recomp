def main():
    changed = 0
    langs = sorted({l for t in T.values() for l in t})
    for lang in langs:
        path = I18N / f"{lang}.po"
        text = path.read_text(encoding="utf-8")
        for ctx, trans in T.items():
            if lang not in trans:
                continue
            msgid = re.search(r'msgctxt "' + ctx + r'"\nmsgid "(.*)"\n', text)
            if not msgid:
                print(f"{lang}: no entry {ctx}, regenerate the catalog first")
                continue
            # only fill empty translations; never touch a translator's words
            pat = (f'msgctxt "{ctx}"\nmsgid "{msgid.group(1)}"\nmsgstr ""')
            new = (f'msgctxt "{ctx}"\nmsgid "{msgid.group(1)}"\nmsgstr "{trans[lang]}"')
            if pat in text:
                text = text.replace(pat, new, 1)
                changed += 1
            elif f'msgctxt "{ctx}"\nmsgid "{msgid.group(1)}"\nmsgstr "' not in text:
                print(f"{lang}: {ctx} has no msgstr line?")
        path.write_text(text, encoding="utf-8")
    print(f"filled {changed} empty entries")


if __name__ == "__main__":
    main()
